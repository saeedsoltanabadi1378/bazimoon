export type AdminLang = "en" | "fa";
export type AdminKey = Key;

interface AdminI18n {
  lang: AdminLang;
  setLang(lang: AdminLang): void;
  t(key: Key, vars?: Record<string, string | number>): string;
  n(value: number): string;
  date(value: string | Date, withTime?: boolean): string;
  time(value: string | Date): string;
  ago(value: string | Date | null | undefined): string;
  agoSeconds(seconds: number): string;
}

const STORAGE_KEY = "bazimoon-admin-lang";
const Ctx = createContext<AdminI18n | null>(null);

function initialLang(): AdminLang {
  try {
    return localStorage.getItem(STORAGE_KEY) === "fa" ? "fa" : "en";
  } catch {
    return "en";
  }
}

export function AdminI18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<AdminLang>(initialLang);
  const setLang = useCallback((next: AdminLang) => {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // storage blocked: the choice lasts for this visit
    }
  }, []);

  const value = useMemo<AdminI18n>(() => {
    const locale = lang === "fa" ? "fa-IR" : "en-GB";
    const num = new Intl.NumberFormat(locale);
    const n = (v: number) => num.format(v);
    const t = (key: Key, vars?: Record<string, string | number>) => {
      let text = (lang === "fa" ? fa : en)[key] ?? en[key];
      if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, typeof v === "number" ? n(v) : v);
      return text;
    };
    const tz = { timeZone: "Asia/Tehran" } as const;
    const date = (v: string | Date, withTime = false) =>
      new Date(v).toLocaleDateString(locale, { day: "numeric", month: "short", ...(withTime ? { hour: "2-digit", minute: "2-digit" } : {}), ...tz });
    const time = (v: string | Date) => new Date(v).toLocaleTimeString(locale, { hour: "2-digit", minute: "2-digit", ...tz });
    const agoSeconds = (s: number) =>
      s < 10 ? t("justNow") : s < 60 ? t("secondsAgo", { count: Math.round(s) }) : s < 3600 ? t("minutesAgo", { count: Math.round(s / 60) })
        : s < 86400 ? t("hoursAgo", { count: Math.round(s / 3600) }) : t("daysAgo", { count: Math.round(s / 86400) });
    const ago = (v: string | Date | null | undefined) => (v ? agoSeconds((Date.now() - new Date(v).getTime()) / 1000) : t("none"));
    return { lang, setLang, t, n, date, time, ago, agoSeconds };
  }, [lang, setLang]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useAdminI18n() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useAdminI18n must be used inside AdminI18nProvider");
  return ctx;
}
